# The pitch of every Mipo voice syllable (assets/voices/<speaker>/<syl>.ogg): pYIN over the
# voiced part, its median as the note, how far it glides, where the vowel starts.
# Writes src/voice-pitch-data.lua (what the singing reads) and prints a report.
# usage: python3 -I claudetools/voice-pitch.py [--speakers nikki,theo,herman] [--no-write]
import sys, os, glob, numpy as np, librosa

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
args = sys.argv[1:]
speakers = ['nikki', 'theo', 'herman']
if '--speakers' in args: speakers = args[args.index('--speakers') + 1].split(',')
write = '--no-write' not in args
NAMES = ['C', 'C#', 'D', 'Eb', 'E', 'F', 'F#', 'G', 'Ab', 'A', 'Bb', 'B']

def name(m):
    r = int(round(m)); return f"{NAMES[r % 12]}{r // 12 - 1}"

def steadiest(y, sr, dur):
    # Fallback when pYIN calls it unvoiced (Nikki's takes: rough, octave-jumping): plain YIN on the
    # loud frames, then the longest run whose neighbours stay within a semitone. Marked rough.
    hop = 256
    rms = librosa.feature.rms(y=y, frame_length=1024, hop_length=hop)[0]
    f0 = librosa.yin(y, fmin=70, fmax=900, sr=sr, frame_length=1024, hop_length=hop, trough_threshold=0.3)
    m = librosa.hz_to_midi(f0); n = min(len(m), len(rms)); loud = rms[:n] > rms.max() * 0.3
    best, cur = (0, 0), None
    for i in range(n):
        if loud[i] and cur is not None and abs(m[i] - m[i - 1]) < 1.0: pass
        elif loud[i]: cur = i
        else: cur = None; continue
        if i - cur + 1 > best[1] - best[0]: best = (cur, i + 1)
    a, b = best
    if b - a < 4: return dict(dur=dur, voiced=0)
    run = m[a:b]
    return dict(dur=dur, voiced=(b - a) * hop / sr, midi=float(np.median(run)),
                spread=float(np.percentile(run, 90) - np.percentile(run, 10)),
                glide=float(run[-1] - run[0]), start=a * hop / sr, stop=b * hop / sr, rough=True)

def analyse(path):
    y, sr = librosa.load(path, sr=22050, mono=True)
    hop = 128
    f0, voiced, prob = librosa.pyin(y, fmin=70, fmax=900, sr=sr, frame_length=1024, hop_length=hop)
    ok = voiced & (prob > 0.3) & ~np.isnan(f0)
    dur = len(y) / sr
    if ok.sum() < 6:
        return dict(steadiest(y, sr, dur), peak=float(np.abs(y).max()))
    idx = np.where(ok)[0]
    midi = librosa.hz_to_midi(f0[idx])
    # the steady middle of the vowel: drop the first and last fifth (onset scoop, tail droop)
    n = len(midi); a, b = int(n * 0.2), max(int(n * 0.8), int(n * 0.2) + 1)
    core = midi[a:b]
    t = idx * hop / sr
    return dict(dur=dur, peak=float(np.abs(y).max()), voiced=(idx[-1] - idx[0] + 1) * hop / sr, midi=float(np.median(core)),
                spread=float(np.percentile(core, 90) - np.percentile(core, 10)),
                glide=float(np.median(midi[-max(2, n // 5):]) - np.median(midi[:max(2, n // 5)])),
                start=float(t[0]), stop=float(t[-1]))

results = {}
for sp in speakers:
    results[sp] = {}
    for f in sorted(glob.glob(os.path.join(ROOT, 'assets', 'voices', sp, '*.ogg'))):
        results[sp][os.path.splitext(os.path.basename(f))[0]] = analyse(f)

# A rough reading is often an octave off (YIN on a creaky take): fold it to the octave nearest the
# speaker's clean readings. The note within the octave stays a guess; 'rough' says so.
for sp, rows in results.items():
    clean = [r['midi'] for r in rows.values() if r.get('voiced') and not r.get('rough')]
    if not clean: continue
    ref = float(np.median(clean))
    for r in rows.values():
        if r.get('rough') and r.get('voiced'):
            k = round((ref - r['midi']) / 12)
            if k: r['midi'] += 12 * k; r['folded'] = 12 * k

print("syllable  note   midi    cents  ->C4 st  glide st  wobble st  vowel from-to (s)  dur")
for sp, rows in results.items():
    ms = [r['midi'] for r in rows.values() if r.get('voiced')]
    med = float(np.median(ms)) if ms else 0
    print(f"\n== {sp}: {len(rows)} syllables, median {name(med)} ({med:.1f}), range {name(min(ms))}-{name(max(ms))} ({max(ms)-min(ms):.1f} st)")
    for syl, r in rows.items():
        if not r.get('voiced'):
            print(f"{syl:8}  (no pitch)                                                    {r['dur']:.2f}"); continue
        cents = (r['midi'] - round(r['midi'])) * 100
        flag = ('  <- rough' + (f", folded {r['folded']:+d}" if r.get('folded') else '')) if r.get('rough') else '  <- glides' if abs(r['glide']) > 1.5 else ('  <- wobbly' if r['spread'] > 1.0 else '')
        print(f"{syl:8}  {name(r['midi']):5} {r['midi']:6.2f}  {cents:+5.0f}  {60 - r['midi']:+7.2f}  {r['glide']:+7.2f}  {r['spread']:8.2f}"
              f"   {r['start']:.2f}-{r['stop']:.2f}          {r['dur']:.2f}{flag}")

if write:
    out = ["-- Generated by claudetools/voice-pitch.py: the pitch of each Mipo voice syllable.",
           "-- midi = median pitch of the vowel's steady middle (60 = middle C); glide = semitones end minus start;",
           "-- spread = 10-90% wobble in semitones; start/stop = where the vowel is voiced (s); dur = file length (s);",
           "-- peak = the loudest sample (0..1), to even out loudness.",
           "-- luacheck: no max line length",
           "return {"]
    for sp, rows in results.items():
        out.append(f"  {sp} = {{")
        for syl, r in rows.items():
            if not r.get('voiced'):
                out.append(f"    ['{syl}'] = {{ dur = {r['dur']:.3f}, peak = {r.get('peak', 1):.3f} }},"); continue
            out.append(f"    ['{syl}'] = {{ midi = {r['midi']:.2f}, glide = {r['glide']:.2f}, spread = {r['spread']:.2f}, "
                       f"start = {r['start']:.3f}, stop = {r['stop']:.3f}, dur = {r['dur']:.3f}, peak = {r['peak']:.3f}"
                       + (", rough = true" if r.get('rough') else "") + " },")
        out.append("  },")
    out.append("}")
    with open(os.path.join(ROOT, 'src', 'voice-pitch-data.lua'), 'w') as fh: fh.write("\n".join(out) + "\n")
    print("\nwrote src/voice-pitch-data.lua")
