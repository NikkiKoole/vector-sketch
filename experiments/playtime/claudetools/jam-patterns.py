#!/usr/bin/env python3
"""Generate src/music-jam-patterns.lua (the drum jam's patterns, docs/DRUM-JAM.md) from dreamengine's
tools/drum-patterns.json: 565 named 16-step patterns in 92 groups, one grid per role (BD SD CPS CH OH CY
RS CB LT MT HT TB, AC = accent), a step being 'x' (hit), 'f' (flam) or '.'.

usage: python3 -I claudetools/jam-patterns.py [group ...]   (default: the groups the jam uses)
env:   DREAMENGINE=/path/to/dreamengine (default ~/Projects/dreamengine)

The output is GENERATED: rerun this, don't edit it. Provenance is uneven (dreamengine's runtime/drumpat.h:
the maker's own drum-patterns.lua, citing "Drum Machine - 260 Patterns" for its core set only).
"""
import json
import os
import sys

GROUPS = ['Electro', 'BoomBAP', 'CR78'] # Nikki's pick (2026-11-02); add a group here and rerun

here = os.path.dirname(os.path.abspath(__file__))
engine = os.environ.get('DREAMENGINE', os.path.expanduser('~/Projects/dreamengine'))
src = os.path.join(engine, 'tools', 'drum-patterns.json')
out = os.path.join(here, '..', 'src', 'music-jam-patterns.lua')
want = sys.argv[1:] or GROUPS

with open(src, encoding='utf-8') as f:
    machines = {m['name']: m for m in json.load(f)['machines']}
missing = [g for g in want if g not in machines]
if missing:
    sys.exit('not in %s: %s' % (src, ', '.join(missing)))

def lua_str(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"

lines = [
    '-- luacheck: no max line length',
    '-- GENERATED by claudetools/jam-patterns.py from dreamengine tools/drum-patterns.json. Do not edit:',
    '-- rerun it. The drum jam\'s patterns (docs/DRUM-JAM.md): per group, its sections, each a 16-step grid',
    "-- per role (BD SD CPS CH OH CY RS CB LT MT HT TB; AC = accent), a step 'x' (hit), 'f' (flam) or '.'.",
    '-- Provenance is uneven (see the script): fine to play, not to call "the real X".',
    'return {',
]
total = 0
for g in want:
    lines.append('    [%s] = {' % lua_str(g))
    for sec in machines[g]['sections']:
        grid = ', '.join('%s = %s' % (role, lua_str(steps)) for role, steps in sorted(sec['grid'].items())
                         if len(steps) == 16)
        lines.append('        { name = %s, grid = { %s } },' % (lua_str(sec['name']), grid))
        total += 1
    lines.append('    },')
lines.append('}')
with open(out, 'w', encoding='utf-8') as f:
    f.write('\n'.join(lines) + '\n')
print('wrote %s: %d groups, %d patterns' % (os.path.relpath(out), len(want), total))
