#!/usr/bin/env python3
"""Generate src/music-jam-patterns.lua (the drum jam's patterns, docs/DRUM-JAM.md) from dreamengine's
tools/drum-patterns.json: 565 named 16-step patterns in 92 groups, one grid per role (BD SD CPS CH OH CY
RS CB LT MT HT TB, AC = accent), a step being 'x' (hit), 'f' (flam) or '.'.

The jam plays FAMILIES, not single patterns: the variants of one groove (ELECTRO 1 - A / - B, AMEN BREAK
- A..D, a book group's Measure A / Measure B) plus, where the source has one, its written fill (the book
groups' Break). GENRES below picks them (2026-11-02, from an analysis of every group: only families with
at least two distinct variants; docs/DRUM-JAM.md has the table and the reasons). Identical grids are
dropped (Electro repeats four of its sections).

usage: python3 -I claudetools/jam-patterns.py
env:   DREAMENGINE=/path/to/dreamengine (default ~/Projects/dreamengine)

The output is GENERATED: rerun this, don't edit it. Provenance is uneven (dreamengine's runtime/drumpat.h:
the maker's own drum-patterns.lua, citing "Drum Machine - 260 Patterns" for its core set only).
"""
import json
import os
import re
import sys

# genre -> (source groups, the families to keep; None = every family of those groups with variants)
GENRES = [
    ('Electro', ['Electro'], ['ELECTRO 1', 'ELECTRO 3']),
    ('Hip Hop', ['Hip Hop'], ['HIP HOP 1', 'HIP HOP 2', 'HIP HOP 3', 'HIP HOP 4']),
    ('Breaks', ['Funk and Soul'], ['AMEN BREAK', 'CISSY STRUT (B-SECTION)', 'HOOK AND SLING', 'KISSING MY LOVE']),
    ('Disco', ['Disco 1', 'Disco 2', 'Disco 3', 'Disco 4', 'Disco 5'], None),
    ('Funk', ['Funk 1', 'Funk 3', 'Funk 6', 'Funk 7', 'Funk 11', 'Funk 12'], None),
]
BOOK = re.compile(r'^(Funk|Disco|Rhythm & Blues|Afro-Cuban|Rock|Pop|Reggae|Ballad|Samba) [0-9]')

here = os.path.dirname(os.path.abspath(__file__))
engine = os.environ.get('DREAMENGINE', os.path.expanduser('~/Projects/dreamengine'))
src = os.path.join(engine, 'tools', 'drum-patterns.json')
out = os.path.join(here, '..', 'src', 'music-jam-patterns.lua')

with open(src, encoding='utf-8') as f:
    machines = {m['name']: m for m in json.load(f)['machines']}

def families(group):
    """{family name: {'loops': [...], 'fill': section or None}} for one source group, duplicates dropped."""
    fams, seen = {}, set()
    for sec in machines[group]['sections']:
        grid = {r: v for r, v in sec['grid'].items() if len(v) == 16}
        key = json.dumps(sorted(grid.items()))
        if key in seen:
            continue
        seen.add(key)
        if BOOK.match(group): # a book group is one family: Measure A, Measure B, Break
            base, is_fill = group, sec['name'].lower().startswith('break')
        else:
            base, is_fill = re.sub(r' - ([A-D]|RATCHETED)$', '', sec['name']), False
        fam = fams.setdefault(base, {'loops': [], 'fill': None})
        if is_fill:
            fam['fill'] = {'name': sec['name'], 'grid': grid}
        else:
            fam['loops'].append({'name': sec['name'], 'grid': grid})
    return fams

def lua_str(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"

def lua_pattern(p):
    grid = ', '.join('%s = %s' % (r, lua_str(v)) for r, v in sorted(p['grid'].items()))
    return '{ name = %s, grid = { %s } }' % (lua_str(p['name']), grid)

lines = [
    '-- luacheck: no max line length',
    '-- GENERATED by claudetools/jam-patterns.py from dreamengine tools/drum-patterns.json. Do not edit:',
    "-- rerun it. The drum jam's patterns (docs/DRUM-JAM.md): genre -> its families, each family the variants",
    '-- of one groove (loops) and, where the source wrote one, its fill. A grid is 16 steps per role (BD SD CPS',
    "-- CH OH CY RS CB LT MT HT TB; AC = accent), a step 'x' (hit), 'f' (flam) or '.'. Provenance is uneven",
    '-- (see the script): fine to play, not to call "the real X".',
    'return {',
]
counts = []
for genre, groups, keep in GENRES:
    for g in groups:
        if g not in machines:
            sys.exit('not in %s: %s' % (src, g))
    picked = []
    for g in groups:
        for name, fam in families(g).items():
            if len(fam['loops']) >= 2 and (keep is None or name in keep):
                picked.append((name, fam))
    if keep:
        found = {n for n, _ in picked}
        missing = [k for k in keep if k not in found]
        if missing:
            sys.exit('%s: no family with variants named %s' % (genre, ', '.join(missing)))
    lines.append('    [%s] = {' % lua_str(genre))
    for name, fam in picked:
        lines.append('        { name = %s,' % lua_str(name))
        lines.append('          loops = {')
        for p in fam['loops']:
            lines.append('              %s,' % lua_pattern(p))
        lines.append('          },')
        if fam['fill']:
            lines.append('          fill = %s },' % lua_pattern(fam['fill']))
        else:
            lines.append('        },')
    lines.append('    },')
    counts.append('%s %d families' % (genre, len(picked)))
lines.append('}')
with open(out, 'w', encoding='utf-8') as f:
    f.write('\n'.join(lines) + '\n')
print('wrote %s: %s' % (os.path.relpath(out), ', '.join(counts)))
