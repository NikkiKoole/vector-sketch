# Bake Mipo voice syllables re-tuned with the WORLD vocoder (docs/CHOIR.md): each take's pitch curve is
# moved to a grid of pitches (its own little melody kept), the throat and the length stay. The game picks
# the nearest baked pitch and resamples the rest (<= 1.5 semitones). Writes
# assets/voices-baked/<speaker>/<syllable>/<midi>.ogg and assets/voices-baked/index.lua
# (generated, not in git: run it again to remake them).
# Needs pyworld: python3 -m venv --system-site-packages /tmp/venv && /tmp/venv/bin/pip install pyworld
# usage: /tmp/venv/bin/python -I claudetools/voice-bake.py [--step 3] [--low 42] [--high 72]
#        (syllables: the ones the choir's tunes sing, read from scripts/spikes/choir.playtime.lua)
import sys, os, re, shutil, numpy as np, librosa, pyworld as pw, soundfile as sf

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
args = sys.argv[1:]
def opt(name, default):
    return float(args[args.index(name) + 1]) if name in args else default
STEP, LOW, HIGH = opt('--step', 3), opt('--low', 42), opt('--high', 72)
FS, FP = 44100, 5.0
SPEAKERS = ['theo', 'herman', 'nikki']
OUT = os.path.join(ROOT, 'assets', 'voices-baked')

scene = open(os.path.join(ROOT, 'scripts', 'spikes', 'choir.playtime.lua')).read()
syllables = sorted(set(re.findall(r"\{ [A-G]\d, [^,]+, '(\w+)' \}", scene)))
data = {}
txt = open(os.path.join(ROOT, 'src', 'voice-pitch-data.lua')).read()
for sp, body in re.findall(r"  (\w+) = \{\n(.*?)\n  \},", txt, re.S):
    for syl, fields in re.findall(r"\['(\w+)'\] = \{ (.*?) \}", body):
        data[(sp, syl)] = {k: v for k, v in re.findall(r"(\w+) = ([\w.\-]+)", fields)}

grid = list(np.arange(LOW, HIGH + 0.01, STEP))
if os.path.isdir(OUT): shutil.rmtree(OUT)
index = ["-- Generated by claudetools/voice-bake.py: WORLD re-tuned takes, assets/voices-baked/<sp>/<syl>/<midi>.ogg.",
         "-- Per take: the pitches baked, the vowel's start (s, unchanged: WORLD keeps the length) and each file's peak.",
         "return {"]
count = 0
for sp in SPEAKERS:
    index.append(f"  {sp} = {{")
    for syl in syllables:
        d = data.get((sp, syl))
        path = os.path.join(ROOT, 'assets', 'voices', sp, f"{syl}.ogg")
        if not d or 'midi' not in d or not os.path.exists(path): continue
        midi = float(d['midi'])
        y, _ = librosa.load(path, sr=FS, mono=True)
        y = y.astype(np.float64)
        f0, t = pw.harvest(y, FS, f0_floor=70, f0_ceil=900, frame_period=FP)
        spec, ap = pw.cheaptrick(y, f0, t, FS), pw.d4c(y, f0, t, FS)
        os.makedirs(os.path.join(OUT, sp, syl), exist_ok=True)
        peaks = []
        for g in grid:
            out = pw.synthesize(f0 * 2 ** ((g - midi) / 12), spec, ap, FS, FP)
            peak = float(np.abs(out).max()) + 1e-9
            sf.write(os.path.join(OUT, sp, syl, f"{int(g)}.ogg"), (out / peak * 0.9).astype(np.float32), FS,
                     format='OGG', subtype='VORBIS')
            peaks.append(f"[{int(g)}] = 0.9")
            count += 1
        index.append(f"    ['{syl}'] = {{ start = {d.get('start', '0')}, rough = {'true' if d.get('rough') else 'false'}, "
                     f"pitches = {{ {', '.join(peaks)} }} }},")
    index.append("  },")
index.append("}")
with open(os.path.join(OUT, 'index.lua'), 'w') as fh: fh.write("\n".join(index) + "\n")
size = sum(os.path.getsize(os.path.join(dp, f)) for dp, _, fs in os.walk(OUT) for f in fs)
print(f"baked {count} files ({len(syllables)} syllables x {len(SPEAKERS)} speakers x {len(grid)} pitches "
      f"{int(LOW)}-{int(HIGH)} every {STEP:g}), {size / 1e6:.1f} MB -> assets/voices-baked/")
